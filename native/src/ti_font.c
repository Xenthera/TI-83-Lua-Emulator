static const uint8_t *glyph(char ch) {
  ch = (char)toupper((unsigned char)ch);
  if (ch >= '0' && ch <= '9') {
    static const uint8_t *const dig[] = {
      G_0, G_1, G_2, G_3, G_4, G_5, G_6, G_7, G_8, G_9
    };
    return dig[ch - '0'];
  }
  if (ch >= 'A' && ch <= 'Z') {
    static const uint8_t *const alpha[] = {
      G_A, G_B, G_C, G_D, G_E, G_F, G_G, G_H, G_I, G_J, G_K, G_L, G_M,
      G_N, G_O, G_P, G_Q, G_R, G_S, G_T, G_U, G_V, G_W, G_X, G_Y, G_Z
    };
    return alpha[ch - 'A'];
  }
  switch (ch) {
    case '-': return G_MINUS;
    case '+': return G_PLUS;
    case '*': return G_STAR;
    case '/': return G_SLASH;
    case '.': return G_DOT;
    case '(': return G_LPAREN;
    case ')': return G_RPAREN;
    case '=': return G_EQ;
    case '>': return G_GT;
    case ':': return G_COLON;
    default: return G_SPACE;
  }
}

void ti_font_draw_char(TiLcd *lcd, int x, int y, char ch, bool on) {
  const uint8_t *g = glyph(ch);
  for (int row = 0; row < 8; row++) {
    uint8_t bits = g[row];
    for (int col = 0; col < 7; col++) { /* leave 1px gap -> 6 wide cell feel */
      if (bits & (0x80u >> col)) {
        ti_lcd_set_pixel(lcd, x + col, y + row, on);
      }
    }
  }
}

void ti_font_draw_text(TiLcd *lcd, int x, int y, const char *s, bool on) {
  if (!s) return;
  int cx = x;
  for (; *s; s++) {
    if (*s == '\n') {
      cx = x;
      y += TI_FONT_CELL_H;
      continue;
    }
    ti_font_draw_char(lcd, cx, y, *s, on);
    cx += TI_FONT_CELL_W;
  }
}

int ti_font_text_width(const char *s) {
  if (!s) return 0;
  return (int)strlen(s) * TI_FONT_CELL_W;
}
