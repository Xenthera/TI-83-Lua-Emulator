-- Generate ui/keypads/<machine>.lua seeds from the current Love keypad KEYS tables.
-- Run: tools/luajit/luajit.exe tools/seed_keypad_layouts.lua

local function find_root()
  local p = (arg and arg[0] or ""):gsub("\\", "/")
  local root = p:match("^(.*)/tools/seed_keypad_layouts%.lua$")
  if root and root ~= "" then return root end
  -- cwd is usually the repo root when invoked as tools/luajit/... tools/seed_...
  local f = io.open("ui/keypads/format.lua", "r")
  if f then f:close(); return "." end
  f = io.open("../ui/keypads/format.lua", "r")
  if f then f:close(); return ".." end
  return "."
end

