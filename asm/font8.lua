local CHARSET = " !-./0123456789:ABCDEFGHIJKLMNOPQRSTUVWXYZ"
-- Index map for ROM: glyph index = position in CHARSET (0-based), 8 bytes each.

local function index_of(ch)
  local i = CHARSET:find(ch, 1, true)
  if not i then
    return CHARSET:find(" ", 1, true) - 1
  end
  return i - 1
end

local function glyph(ch)
  ch = ch:upper()
  return Glyphs[ch] or Glyphs[" "]
end

-- Emit packed font blob in CHARSET order for the ROM.
local function blob()
  local bytes = {}
  for i = 1, #CHARSET do
    local g = glyph(CHARSET:sub(i, i))
    for r = 1, 8 do
      bytes[#bytes + 1] = g[r]
    end
  end
  return bytes, CHARSET
end

-- Host-side reference renderer into a 96x64 / 12-byte-row framebuffer table.
local function render_string(fb, text, col, row)
  -- col: byte column 0-11, row: pixel row 0-56
  text = text:upper()
  for i = 1, #text do
    local ch = text:sub(i, i)
    local g = glyph(ch)
    local c = col + i - 1
    if c >= 0 and c <= 11 then
      for r = 0, 7 do
        local y = row + r
        if y >= 0 and y <= 63 then
          fb[y * 12 + c] = g[r + 1]
        end
      end
    end
  end
end

local function new_fb()
  local fb = {}
  for i = 0, 12 * 64 - 1 do
    fb[i] = 0
  end
  return fb
end

return {
  Glyphs = Glyphs,
  CHARSET = CHARSET,
  glyph = glyph,
  index_of = index_of,
  blob = blob,
  render_string = render_string,
  new_fb = new_fb,
}
